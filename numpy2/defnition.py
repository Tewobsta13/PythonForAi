
# AI, ML, DL, and Data Science
#
# AI (Artificial Intelligence):
# A field of computer science focused on building systems
# that perform tasks requiring human-like intelligence.
#
# ML (Machine Learning):
# A subset of AI where algorithms learn patterns from data.
# Algorithm: A method used to learn patterns or solve a problem.
# Model: The result of training an algorithm on data.
# Training: The process of learning patterns from training data.
# Inference: Using a trained model on new input data.
# Prediction: The output produced by a trained model.
#
# Common ML tasks:
# Regression: Predicting numerical values, e.g., house prices.
# Classification: Predicting categories, e.g., spam or not spam.
#
# Types of ML:
# Supervised Learning: Learns from labeled data.
# Unsupervised Learning: Finds patterns in unlabeled data.
# Reinforcement Learning: Learns through actions and rewards.
#
# DL (Deep Learning):
# A subset of ML that uses neural networks with multiple layers
# to learn complex patterns from data.
# Examples: Image recognition, speech recognition, and NLP.
#
# Data Science:
# Uses programming, statistics, and domain knowledge to extract
# useful insights from data and support decision-making.
#
# Typical Data Science workflow:
# 1. Data collection
# 2. Data cleaning
# 3. Exploratory Data Analysis (EDA)
# 4. Data visualization
# 5. Statistical analysis
# 6. Modeling (optional)
# 7. Communicating results
#
# Useful Python libraries:
# NumPy: Numerical operations and arrays.
# pandas: Data manipulation and analysis.
# Matplotlib: Data visualization.
# scikit-learn: Traditional machine learning.
# PyTorch / TensorFlow: Deep learning.
#
# Relationship:
# Deep Learning is a subset of Machine Learning.
# Machine Learning is a subset of Artificial Intelligence.
# Data Science overlaps with AI/ML but is a separate field.
